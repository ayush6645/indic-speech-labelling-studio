def is_pure_silence_audio(audio_path: Path) -> bool:
    """Fast local check for pure digital silence / near-zero audio slices."""
    if sf is None or np is None:
        return False
    try:
        data, _ = sf.read(str(audio_path))
        if data.size == 0:
            return True
        rms = float(np.sqrt(np.mean(np.square(data))))
        peak = float(np.max(np.abs(data)))
        return rms < 0.0005 and peak < 0.005
    except Exception:
        return False


def get_partial_calls_remaining() -> tuple[int, int, float]:
    """Returns (partial_call_count, remaining_unverified_pieces, remaining_hours)."""
    if not DB_PATH.exists():
        return 0, 0, 0.0
    conn = sqlite3.connect(str(DB_PATH), timeout=60.0)
    try:
        row = conn.execute("""
            SELECT
                COUNT(DISTINCT p.call_id),
                COUNT(*),
                COALESCE(SUM(p.duration_s), 0) / 3600.0
            FROM pieces p
            WHERE p.status = 'unverified'
              AND (p.verified_by IS NULL OR p.verified_by = '')
              AND p.call_id IN (
                  SELECT call_id FROM pieces
                  GROUP BY call_id
                  HAVING SUM(CASE WHEN status = 'verified' THEN 1 ELSE 0 END) > 0
                     AND SUM(CASE WHEN status = 'unverified' THEN 1 ELSE 0 END) > 0
              )
        """).fetchone()
        if not row:
            return 0, 0, 0.0
        return int(row[0] or 0), int(row[1] or 0), float(row[2] or 0.0)
    finally:
        conn.close()


def detect_language(native_out: str, piece_data: dict) -> str:
    """Classifies the transcribed native script into its own exact language category."""
    if not native_out:
        return "none"

    bn_cnt = len(re.findall(r"[\u0980-\u09FF]", native_out))
    dev_cnt = len(re.findall(r"[\u0900-\u097F]", native_out))
    te_cnt = len(re.findall(r"[\u0C00-\u0C7F]", native_out))
    kn_cnt = len(re.findall(r"[\u0C80-\u0CFF]", native_out))

    counts = {"bn": bn_cnt, "dev": dev_cnt, "te": te_cnt, "kn": kn_cnt}
    best_script, best_cnt = max(counts.items(), key=lambda kv: kv[1])

    if best_cnt == 0:
        return "en"
    if best_script == "bn":
        return "bn"
    if best_script == "te":
        return "te"
    if best_script == "kn":
        return "kn"

    # Devanagari: distinguish Marathi (mr) vs Hindi (hi)
    draft_lang = (piece_data.get("draft_language") or "").strip().lower()
    call_lang = (piece_data.get("call_language") or "").strip().lower()
    call_state = (piece_data.get("call_state") or "").strip().lower()
    call_id = (piece_data.get("call_id") or "").lower()

    mr_hits = sum(1 for w in MARATHI_MARKERS if w in native_out)
    if mr_hits >= 2:
        return "mr"
    if draft_lang == "mr":
        return "mr"
    if ("maharashtra" in call_state or "maharashtra" in call_id) and (call_lang == "mr" or mr_hits >= 1):
        return "mr"
    return "hi"


def is_silent_response(native_out: str, roman_out: str) -> bool:
    n_low = native_out.strip().lower()
    r_low = roman_out.strip().lower()
    markers = ("silent", "[silence]", "(silence)", "no speech", "no intelligible speech", "silence only")
    return (
        n_low in markers
        or r_low in markers
        or n_low.startswith("silent")
        or "no speech" in n_low
        or "only silence" in n_low
        or "no human speech" in n_low
    )


def parse_ai_response(text: str) -> tuple[str, str]:
    sep = "=== OUTPUT BELOW ==="
    if sep in text:
        text = text.split(sep)[-1]
    elif "Strict Format:" in text:
        text = text.split("Strict Format:")[-1]

    low = text.lower()
    if (
        "no response available" in low
        or "try asking a different question" in low
        or "hit your ai mode limit" in low
        or "come back at" in low
    ):
        return "", ""

    cutoff_patterns = [
        r"Would you like me to.*",
        r"If you have more audio.*",
        r"If you have another audio.*",
        r"AI can make mistakes.*",
        r"Skip to previous.*",
        r"AI Mode response is ready.*",
    ]
    cleaned = text
    for cp in cutoff_patterns:
        cleaned = re.split(cp, cleaned, flags=re.IGNORECASE | re.DOTALL)[0]

    split_match = re.search(r"[*_#\s]*Romanized[^\n:]*[:\n\-*]+\s*", cleaned, flags=re.IGNORECASE)
    if split_match:
        native_part = cleaned[:split_match.start()]
        roman_part = cleaned[split_match.end():]
    else:
        return "", ""

    native_part = re.sub(r"^.*?[*_#\s]*Native[^\n:]*[:\n\-*]+\s*", "", native_part, flags=re.IGNORECASE | re.DOTALL)
    native_part = re.sub(r"(?:Native|Romanized)\s*(?:Transcription|Script|Text)?(?:\s*\([^)]*\))?[:\s]*", "", native_part, flags=re.IGNORECASE)
    roman_part = re.sub(r"(?:Native|Romanized)\s*(?:Transcription|Script|Text)?(?:\s*\([^)]*\))?[:\s]*", "", roman_part, flags=re.IGNORECASE)

    native_part = re.sub(r"[*_`#>]", "", native_part)
    roman_part = re.sub(r"[*_`#>]", "", roman_part)

    native_part = re.sub(r"\s+", " ", native_part).strip()
    roman_part = re.sub(r"\s+", " ", roman_part).strip()

    if len(native_part) < 2 or len(roman_part) < 2:
        return "", ""

    return native_part, roman_part


def compute_sleep_until_reset(body: str) -> tuple[int, str]:
    """Parses 'Come back at 11:48 am IST' into exact seconds to sleep (+15s buffer)."""
    norm = body.replace("\u202f", " ").replace("\u00a0", " ")
    m = re.search(r"Come back at\s+(\d{1,2}):(\d{2})\s*(am|pm)", norm, re.IGNORECASE)
    if not m:
        return 180, "unknown reset time (default 3m)"

    hr = int(m.group(1))
    mn = int(m.group(2))
    ampm = m.group(3).lower()
    reset_str = f"{hr}:{mn:02d} {ampm} IST"

    if ampm == "pm" and hr != 12:
        hr += 12
    elif ampm == "am" and hr == 12:
        hr = 0

    now = dt.datetime.now()
    target = now.replace(hour=hr, minute=mn, second=15, microsecond=0)
    if target <= now:
        delta_past = (now - target).total_seconds()
        if delta_past < 120:
            return 20, reset_str
        target += dt.timedelta(days=1)

    wait_sec = int((target - now).total_seconds())
    wait_sec = max(15, min(wait_sec, 65 * 60))
    return wait_sec, reset_str


def is_rate_limited(body: str) -> bool:
    low = body.lower()
    return (
        "hit your ai mode limit" in low
        or "come back at" in low
        or "not currently available" in low
    )


def handle_rate_limit(page_ai, worker_name: str, body: str) -> bool:
    if not is_rate_limited(body):
        return False

    wait_sec, reset_str = compute_sleep_until_reset(body)
    log("\n" + "=" * 65)
    log(f"[RATE LIMIT - {worker_name}] Google AI Mode quota reached.")
    log(f"Notice: 'Come back at {reset_str}' -> Sleeping cleanly for {wait_sec}s ({wait_sec/60:.1f} min)...")
    log("=" * 65)

    slept = 0
    while slept < wait_sec:
        chunk = min(15, wait_sec - slept)
        time.sleep(chunk)
        slept += chunk

    log(f"[COOLDOWN DONE - {worker_name}] Reset window ({reset_str}) reached! Resuming...")
    return True


