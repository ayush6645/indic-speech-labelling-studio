def wait_for_internet(worker_name: str, check_interval: int = 10):
    """Pauses gracefully if Wi-Fi/DNS drops instead of skipping pieces."""
    logged = False
    while True:
        try:
            s = socket.create_connection(("www.google.com", 443), timeout=5)
            s.close()
            if logged:
                log(f"[NETWORK RESTORED - {worker_name}] Internet is back online! Resuming...")
            return
        except Exception:
            if not logged:
                log(f"[NETWORK OFFLINE - {worker_name}] Cannot reach google.com. Waiting for internet reconnection...")
                logged = True
            time.sleep(check_interval)


def safe_goto(page, url: str, worker_name: str, max_retries: int = 4) -> bool:
    for attempt in range(max_retries):
        try:
            page.goto(url, wait_until="domcontentloaded", timeout=15000)
            return True
        except Exception as e:
            err_str = str(e)
            log(f"[{worker_name}] Navigation error attempt {attempt+1}/{max_retries}: {e}. Retrying in 3s...")
            if "ERR_NAME_NOT_RESOLVED" in err_str or "ERR_INTERNET_DISCONNECTED" in err_str or "ERR_NETWORK_CHANGED" in err_str:
                wait_for_internet(worker_name)
            else:
                time.sleep(3)
    return False


