PROMPT_TEMPLATE = """Draft Reference Context (Warning: This draft was generated by an imperfect ASR model and may contain errors. Listen to the audio slice directly as the ground truth):
Draft Native : {draft_text}
Draft Roman  : {draft_text_roman}

Listen to the attached audio slice directly, verbatim raw text spoken in the audio without punctuation, write numbers as digits, no grammar correction or translation. Return the transcription in both native script and phonetic romanized Latin script. If English is spoken, both native and romanized should be in English. If Hindi or another Indic language is spoken, native should be in the authentic Indic script and romanized in Latin script.

Strict Format:
Native:
Romanized:
=== OUTPUT BELOW ==="""

