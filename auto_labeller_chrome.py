"""
Automated Chrome workflow for Indic Speech Labelling Studio
Replicates the exact steps from the user video:
1. Opens Labelling Tool (http://127.0.0.1:8092) and clean Google AI Mode (https://www.google.com/?udm=50)
2. Uses "+" button -> "Add files" -> file chooser to attach the audio slice (.flac) FIRST
3. Fills prompt with original draft transcription context + strict formatting instructions
4. Submits prompt and waits for Gemini transcription
5. Accurately extracts clean Native & Romanized text without headers, labels or cross-contamination
6. Clears previous text in Labelling Tool and injects corrected text into exact textareas
7. Selects matching language (Hindi for Devanagari, English for Latin) and clicks Verify
8. Logs each action to labelling_data/automation_log.jsonl for instant rollback via revert_automation.py
9. Automatically stops when 10.0 hours of verified audio is reached for any language
"""

