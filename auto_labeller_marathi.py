"""
Automated Chrome workflow for Marathi Indic Speech Labelling
Dedicated worker focusing exclusively on Marathi (mr) calls:
1. Targets unverified Marathi pieces (draft_language='mr' or main_language='mr')
2. Uses Google AI Mode (https://www.google.com/?udm=50) to attach the audio slice (.flac) directly
3. Instructs Gemini to prioritize audio accuracy over noisy v3 drafts
4. Extracts clean Native Marathi script (मराठी) and phonetic Romanized text without headers
5. Automatically marks main_language as 'mr' in the Labelling Tool and verifies
6. Logs all changes to labelling_data/automation_log_marathi.jsonl for instant rollback via revert_marathi.py
7. Automatically stops once all Marathi pieces are completed or target hours reached
"""

